// לפני מילה: ו = ו, ד = ש־ / של, ב = ב, ל = ל, כ = כ, מ = מ
const PREFIX = { ו: 'ו', ד: 'ש', ב: 'ב', ל: 'ל', כ: 'כ', מ: 'מ' };

/** The meaning of the prefix letters `pre` (innermost last) put in front of `meaning`. */
function withPrefix(pre, meaning) {
  let out = meaning;
  for (const ch of [...pre].reverse()) {
    if (ch === 'ד') out = /^ה/.test(out) ? `של ${out}` : `ש${out}`;
    else if ('בלכ'.includes(ch) && /^ה[א-ת]/.test(out)) out = `${ch}${out.slice(1)}`; // ב + העולם = בעולם
    else out = `${PREFIX[ch]}${out}`;
  }
  return out;
}

/** The meaning of an Aramaic word from the built-in dictionary (prefixes ו/ד/ב/ל/כ/מ taken off), or null. */
export function glossOf(word) {
  const w = bareWord(word);
  if (GLOSSARY[w]) return { word: w, stem: w, meaning: GLOSSARY[w] };
  for (let n = 1; n <= 2; n += 1) {
    const pre = w.slice(0, n);
    const stem = w.slice(n);
    if (stem.length < 2 || ![...pre].every((ch) => PREFIX[ch])) continue;
    if (GLOSSARY[stem]) return { word: w, stem, meaning: GLOSSARY[stem].split(' / ').map((m) => withPrefix(pre, m)).join(' / ') };
  }
  return null;
}

/** Forms worth looking up in an online dictionary: the word, then without its prefixes. */
export function stemsOf(word) {
  const w = bareWord(word);
  const out = [w];
  for (let n = 1; n <= 2; n += 1) {
    const pre = w.slice(0, n);
    if (w.length - n >= 3 && [...pre].every((ch) => PREFIX[ch])) out.push(w.slice(n));
  }
  return [...new Set(out)];
}

// in the dictionary, but common in Hebrew too: a tap on them alone does not open the Aramaic popover
const SHARED = new Set('אמר כגון הואיל אדרבה קדם תו חד גו אתא אתי עלם בתר אורח אתר מלה אנא ברא רבא סבא עליה עלה יאות פשיטא מנא כולי עילא'.split(' '));

export function looksAramaic(word) {
  const w = bareWord(word);
  if (!/^[א-ת]{2,}$/.test(w) || NOT_ARAMAIC.has(w)) return false;
  const core = w.replace(/^[ודבלכ]{1,2}(?=[א-ת]{3,})/, '');
  const g = glossOf(w);
  return ARAMAIC_WORDS.has(w) || ARAMAIC_WORDS.has(core) || (!!g && !SHARED.has(g.stem)) || /^ד[א-ת]{2,}א$/.test(w) || (w.length >= 4 && /תא$/.test(w)) || (w.length >= 5 && /(נא|יהו|ייהו)$/.test(w));
}

/**
 * The Aramaic phrase that `word` stands in, inside `sentence`: the run of Aramaic-looking words around it.
 * A selection of several words is taken as it is.
 */
export function aramaicPhrase(sentence, word) {
  const picked = String(word || '').trim();
  if (/\s/.test(picked)) return picked.split(/\s+/).filter((w) => bareWord(w)).slice(0, 24);
  const words = String(sentence || '').split(/[\s,;:!?.()[\]]+/).filter((w) => bareWord(w));
  const target = bareWord(picked);
  const i = words.findIndex((w) => bareWord(w) === target);
  if (i < 0) return target ? [target] : [];
  let a = i, b = i;
  // one Hebrew-looking word between two Aramaic ones stays in the phrase (לית אתר פנוי מיניה, קודשא בריך הוא)
  const aram = (k) => k >= 0 && k < words.length && looksAramaic(words[k]);
  for (;;) {
    if (i - a >= 10) break;
    if (aram(a - 1)) a -= 1; else if (a - 2 >= 0 && aram(a - 2)) a -= 2; else break;
  }
  for (;;) {
    if (b - i >= 10) break;
    if (aram(b + 1)) b += 1; else if (aram(b + 2)) b += 2; else break;
  }
  return words.slice(a, b + 1);
}
