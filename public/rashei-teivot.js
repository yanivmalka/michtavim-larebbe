// ערכים נוספים שנכתבים לפעמים בגרש במקום בגרשיים
const ALIASES = { 'וכו׳': 'וכו\'', 'הנ״ל': 'הנ"ל' };

/** Normalises quotation marks so dictionary lookups work with ״ and ׳ as well as " and '. */
export const normalize = (w) => String(w || '').replace(/[״“”]/g, '"').replace(/[׳‘’`]/g, '\'');

const HEB = 'א-ת';
const PREFIXES = ['ו', 'ה', 'ב', 'ל', 'מ', 'ש', 'כ', 'ד', 'וד', 'בה', 'לה', 'מה', 'כה', 'וה', 'וב', 'ול', 'ומ', 'וש', 'וכ', 'שה', 'שב', 'של', 'שמ', 'כש', 'לכ', 'וכש', 'ושה', 'ובה', 'ולה'];

/** True for ראשי תיבות (letters " letters) or an abbreviation ending with a geresh (וכו', שי'). */
export function isAcronym(word) {
  const w = normalize(word).replace(/[.,;:!?)(\]\[]+$/, '').replace(/^ה'(?=[\u05D0-\u05EA]+")/, '');
  return new RegExp(`^[${HEB}]+"[${HEB}]+$`).test(w) || new RegExp(`^[${HEB}]+'$`).test(w);
}

const VALUES = { א: 1, ב: 2, ג: 3, ד: 4, ה: 5, ו: 6, ז: 7, ח: 8, ט: 9, י: 10, כ: 20, ך: 20, ל: 30, מ: 40, ם: 40, נ: 50, ן: 50, ס: 60, ע: 70, פ: 80, ף: 80, צ: 90, ץ: 90, ק: 100, ר: 200, ש: 300, ת: 400 };
/** The gematria value of a plain letter group (י"ב → 12), or null if the letters are not in descending order. */
export function gematria(word) {
  const letters = normalize(word).replace(/["']/g, '');
  if (!letters || !/^[א-ת]+$/.test(letters)) return null;
  let total = 0; let last = Infinity;
  for (const ch of letters) {
    const v = VALUES[ch];
    if (!v) return null;
    // allowed orders: descending, plus the exceptions ט"ו and ט"ז
    if (v > last && !(letters === 'טו' || letters === 'טז')) return null;
    total += v; last = v;
  }
  return total;
}

/**
 * Possible expansions of `word` – from the dictionary (with Hebrew prefixes such as ו/ב/ל stripped),
 * then as a number or a year. Returns { stem, prefix, options } or null if nothing is known.
 */
export function expand(word) {
  const w = normalize(word).replace(/^["'.,;:(\[]+/, '').replace(/[.,;:!?)\]]+$/, '').replace(/"$/, '');
  if (!w) return null;
  const tryKey = (k) => DICT[k] || DICT[ALIASES[k]] || null;
  let hit = tryKey(w);
  let prefix = '';
  if (!hit) {
    for (const p of PREFIXES.slice().sort((a, b) => b.length - a.length)) {
      if (w.startsWith(p) && w.length > p.length + 1 && tryKey(w.slice(p.length))) { prefix = p; hit = tryKey(w.slice(p.length)); break; }
    }
  }
  const options = hit ? hit.map((o) => `${prefix}${o}`) : [];
  const letters = w.replace(/^ה'/, '').replace(/["']/g, '');
  const num = (str) => { const v = gematria(str); return v != null && v > 0 ? v : null; };
  if (!hit) {
    // a volume, chapter or paragraph number: חי"ד = חלק 14, ספ"ב = סוף פרק 2, סק"ג = סעיף קטן 3
    for (const [lead, label] of [['ספ', 'סוף פרק'], ['סק', 'סעיף קטן'], ['ח', 'חלק']]) {
      if (/"/.test(w) && letters.startsWith(lead) && letters.length > lead.length && num(letters.slice(lead.length)) && num(letters.slice(lead.length)) <= 60) {
        options.push(`${label} ${num(letters.slice(lead.length))}`);
      }
    }
    // a word cut short with a geresh: שיחי' = שיחיה / שיחיו, הי' = היה
    if (/[א-ת]+י'$/.test(w)) {
      const stem = w.slice(0, -1);
      options.push(`${stem}ה`, `${stem}ו`);
    }
  }
  // numbers and years: ב' = 2, י"ב = 12, תשי"ג = שנת 5713
  const core = w.replace(/^ה'/, '');
  const n = gematria(core);
  if (n != null && /^[א-ת]'$/.test(core)) options.push(`${n}`);
  if (n != null && /"/.test(core) && letters.length >= 2 && (!hit || letters.length <= 2)) {
    if (n >= 600 && n < 1000 && !hit) {
      const year = 5000 + n;
      options.push(`שנת ${w} – ${year} לבריאת העולם (${year - 3761}–${year - 3760})`);
    } else if (n <= 400) {
      options.push(`${n} (בגימטריה)`);
    }
  }
  return options.length ? { stem: prefix ? w.slice(prefix.length) : w, prefix, options: [...new Set(options)] } : null;
}

